"""精美的预设配色方案 —— 每套都是可直接用的渐变。"""
import numpy as np

# 每套 palette 是若干 RGB 锚点色，采样时线性插值
PALETTES = {
    "sunset":  [(255, 89, 94), (255, 202, 58), (138, 201, 38), (25, 130, 196), (106, 76, 147)],
    "ocean":   [(0, 24, 61), (0, 59, 92), (0, 113, 141), (82, 182, 154), (169, 222, 249)],
    "candy":   [(255, 154, 200), (255, 183, 178), (186, 148, 222), (120, 199, 211), (255, 236, 209)],
    "forest":  [(18, 41, 27), (34, 85, 51), (85, 153, 99), (164, 205, 135), (233, 245, 210)],
    "neon":    [(15, 15, 35), (114, 9, 183), (247, 37, 133), (255, 184, 77), (76, 201, 240)],
    "mono":    [(20, 20, 30), (70, 70, 90), (140, 140, 160), (220, 220, 230), (255, 255, 255)],
    "peach":   [(255, 179, 179), (255, 223, 179), (255, 255, 179), (179, 255, 223), (179, 217, 255)],
    "gold":    [(40, 25, 5), (120, 80, 20), (212, 175, 55), (255, 230, 150), (255, 250, 220)],
}


def sample_gradient(palette_name: str, t: float) -> np.ndarray:
    """在渐变上取色，t ∈ [0,1]，返回 (3,) float。"""
    stops = np.array(PALETTES.get(palette_name, PALETTES["sunset"]), dtype=np.float64)
    t = np.clip(t, 0.0, 1.0)
    x = t * (len(stops) - 1)
    i = int(np.floor(x))
    j = min(i + 1, len(stops) - 1)
    f = x - i
    return stops[i] * (1 - f) + stops[j] * f
